/**
 * Regenerate api/_lib/cairo-font-data.ts from the Cairo TTFs shipped inside
 * the pdfmake-rtl package. Run whenever pdfmake-rtl's Cairo fonts change:
 *   node scripts/generate-cairo-font-base64.mjs
 */

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");

const CAIRO_DIR = path.join(repoRoot, "node_modules/pdfmake-rtl/fonts/Cairo");
const OUT_FILE = path.join(repoRoot, "lib/cairo-font-data.server.ts");

function readBase64(filename) {
  const filePath = path.join(CAIRO_DIR, filename);
  return fs.readFileSync(filePath).toString("base64");
}

const regular = readBase64("Cairo-Regular.ttf");
const bold = readBase64("Cairo-Bold.ttf");

const contents = `/**
 * Generated by scripts/generate-cairo-font-base64.mjs — do not edit by hand.
 * Base64 of pdfmake-rtl's bundled Cairo-Regular.ttf / Cairo-Bold.ttf, embedded
 * so the serverless function never fetches fonts over the network.
 */

export const CAIRO_REGULAR_BASE64 =
  "${regular}";

export const CAIRO_BOLD_BASE64 =
  "${bold}";
`;

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, contents);

console.log(`Wrote ${OUT_FILE}`);
console.log(`  Cairo-Regular.ttf: ${regular.length} base64 chars`);
console.log(`  Cairo-Bold.ttf:    ${bold.length} base64 chars`);
